async function callClaude(
  system,
  messages,
  maxTokens = 1200
) {

  try {

    const response =
      await axios.post(

        'https://api.anthropic.com/v1/messages',

        {
          model:
            MODEL,

          max_tokens:
            maxTokens,

          system,

          messages,
        },

        {
          headers: {

            'Content-Type':
              'application/json',

            'x-api-key':
              ANTHROPIC_API_KEY,

            'anthropic-version':
              '2023-06-01',
          },

          timeout:
            30000,
        }
      );


    return response.data.content
      .map(
        (block) =>
          block.text || ''
      )
      .join('')
      .trim();

  } catch (err) {

    console.error(
      'تفاصيل خطأ Claude API:',
      JSON.stringify(
        err.response?.data ||
          err.message,
        null,
        2
      )
    );


    return null;
  }
}


