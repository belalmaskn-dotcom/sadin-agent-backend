async function generateReply(history, userText) {

  try {

    const messages = [
      ...history,
      {
        role: 'user',
        content: userText,
      },
    ];


    // ================================================
    // فهم رسالة العميل
    // ================================================

    const rawExtraction = await callClaude(
      EXTRACTION_SYSTEM_PROMPT,
      messages
    );


    // خطأ تقني فقط
    if (!rawExtraction) {

      return `ياهلا فيك 🌹
تقدر تشوف جميع عروضنا من خلال قناة واتساب:
${OFFERS_CHANNEL}

وللاستفسار:
${CONTACT_NUMBER}`;

    }


    // ================================================
    // تنظيف JSON
    // ================================================

    let cleaned = rawExtraction
      .replace(/```json/gi, '')
      .replace(/```/g, '')
      .trim();


    // محاولة أخذ JSON فقط إذا Claude أضاف كلام بالغلط
    const firstBrace = cleaned.indexOf('{');
    const lastBrace = cleaned.lastIndexOf('}');

    if (
      firstBrace !== -1 &&
      lastBrace !== -1 &&
      lastBrace > firstBrace
    ) {
      cleaned = cleaned.slice(
        firstBrace,
        lastBrace + 1
      );
    }


    let parsed;


    // ================================================
    // قراءة JSON
    // ================================================

    try {

      parsed = JSON.parse(cleaned);

    } catch (e) {

      console.error(
        'فشل قراءة JSON من Claude:',
        cleaned
      );

      return `ياهلا فيك 🌹
تقدر تشوف جميع عروضنا من خلال قناة واتساب:
${OFFERS_CHANNEL}

وللاستفسار:
${CONTACT_NUMBER}`;

    }


    // ================================================
    // التأكد من صحة الرد
    // ================================================

    if (!parsed || typeof parsed !== 'object') {

      return `ياهلا فيك 🌹
تقدر تشوف جميع عروضنا من خلال قناة واتساب:
${OFFERS_CHANNEL}

وللاستفسار:
${CONTACT_NUMBER}`;

    }


    // ================================================
    // الرد بدون بحث
    // ================================================

    if (!parsed.ready_to_search) {

      if (
        parsed.reply &&
        typeof parsed.reply === 'string' &&
        parsed.reply.trim()
      ) {

        return parsed.reply.trim();

      }

      return `ياهلا فيك 🌹
عندنا عدة عروض عقارية في المدينة المنورة.
وش نوع العقار اللي تبحث عنه: شقة، فيلا، أو عقار استثماري؟`;

    }


    // ================================================
    // معايير البحث
    // ================================================

    const criteria =
      parsed.criteria &&
      typeof parsed.criteria === 'object'
        ? parsed.criteria
        : {};


    // ================================================
    // البحث
    // ================================================

    let matches = [];

    try {

      matches =
        searchProperties({
          city: criteria.city || null,
          district: criteria.district || null,
          property_type: criteria.property_type || null,
          purpose: criteria.purpose || null,
          limit: 5,
        }) || [];

    } catch (searchError) {

      console.error(
        'خطأ أثناء البحث:',
        searchError
      );

      return `ياهلا فيك 🌹
تقدر تشوف جميع عروضنا المتاحة هنا:
${OFFERS_CHANNEL}

وللاستفسار:
${CONTACT_NUMBER}`;

    }


    // ================================================
    // تجهيز نتائج البحث
    // ================================================

    const resultsContext = matches.length
      ? `نتائج البحث المتاحة فعليًا:\n${matches
          .map((m) => {

            const title =
              m.title ||
              m.property_type ||
              'عقار';

            const location =
              `${m.city || ''} ${m.district || ''}`.trim();

            const area =
              m.area_sqm
                ? `${m.area_sqm} م²`
                : 'المساحة غير مذكورة';

            const url =
              m.url ||
              'لا يوجد رابط';

            return `- ${title} في ${location} — ${area} — ${url}`;

          })
          .join('\n')}`
      : 'لا توجد نتائج مطابقة حاليًا في الفهرس.';


    // ================================================
    // الرد النهائي من نتائج البحث
    // ================================================

    const groundedMessages = [
      ...messages,

      {
        role: 'assistant',
        content: rawExtraction,
      },

      {
        role: 'user',
        content: `[نتائج البحث الداخلية]
${resultsContext}

اكتب الرد النهائي للعميل بناءً على النتائج فقط.`,
      },
    ];


    const finalReply = await callClaude(
      GROUNDED_REPLY_SYSTEM_PROMPT,
      groundedMessages
    );


    if (
      !finalReply ||
      typeof finalReply !== 'string' ||
      !finalReply.trim()
    ) {

      return `ياهلا فيك 🌹
تقدر تشوف جميع عروضنا المتاحة هنا:
${OFFERS_CHANNEL}

وللاستفسار:
${CONTACT_NUMBER}`;

    }


    return finalReply.trim();


  } catch (err) {

    console.error(
      'خطأ غير متوقع في generateReply:',
      err
    );

    return `ياهلا فيك 🌹
تقدر تشوف جميع عروضنا المتاحة هنا:
${OFFERS_CHANNEL}

وللاستفسار:
${CONTACT_NUMBER}`;
  }
}


