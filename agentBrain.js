async function generateReply(history, userText) {

  try {

    const messages = [
      ...history,
      {
        role: 'user',
        content: userText,
      },
    ];


    // ================================================
    // المرحلة الأولى: فهم رسالة العميل
    // ================================================

    const rawExtraction = await callClaude(
      EXTRACTION_SYSTEM_PROMPT,
      messages
    );


    // لو Claude نفسه لم يرجع رد
    if (!rawExtraction) {
      return CONTACT_REPLY;
    }


    // تنظيف الرد
    const cleaned = rawExtraction
      .replace(/```json/gi, '')
      .replace(/```/g, '')
      .trim();


    let parsed;


    // ================================================
    // محاولة قراءة JSON
    // ================================================

    try {

      parsed = JSON.parse(cleaned);

    } catch (e) {

      console.error(
        'فشل قراءة JSON من Claude:',
        cleaned
      );

      // بدل رسالة "حصل خلل بسيط"
      // يتم إرسال رقم التواصل مباشرة
      return CONTACT_REPLY;
    }


    // ================================================
    // التأكد من أن الرد صالح
    // ================================================

    if (!parsed || typeof parsed !== 'object') {
      return CONTACT_REPLY;
    }


    // ================================================
    // لو لا نحتاج البحث
    // ================================================

    if (!parsed.ready_to_search) {

      if (
        parsed.reply &&
        typeof parsed.reply === 'string' &&
        parsed.reply.trim()
      ) {
        return parsed.reply.trim();
      }

      return CONTACT_REPLY;
    }


    // ================================================
    // تجهيز معايير البحث
    // ================================================

    const criteria =
      parsed.criteria &&
      typeof parsed.criteria === 'object'
        ? parsed.criteria
        : {};


    // ================================================
    // البحث في العقارات المحلية
    // ================================================

    let matches = [];

    try {

      matches = searchProperties({
        city: criteria.city || null,
        district: criteria.district || null,
        property_type: criteria.property_type || null,
        purpose: criteria.purpose || null,
        limit: 5,
      }) || [];

    } catch (searchError) {

      console.error(
        'خطأ أثناء البحث عن العقارات:',
        searchError
      );

      return CONTACT_REPLY;
    }


    // ================================================
    // تجهيز نتائج البحث
    // ================================================

    const resultsContext = matches.length
      ? `نتائج البحث المتاحة فعليًا:\n${matches
          .map((m) => {

            const title =
              m.title ||
              m.property_type ||
              'عقار';

            const location =
              `${m.city || ''} ${m.district || ''}`.trim();

            const area =
              m.area_sqm
                ? `${m.area_sqm} م²`
                : 'المساحة غير مذكورة';

            const url =
              m.url ||
              'لا يوجد رابط';

            return `- ${title} في ${location} — ${area} — ${url}`;

          })
          .join('\n')}`
      : 'لا توجد نتائج مطابقة حاليًا في الفهرس.';


    // ================================================
    // إرسال النتائج إلى Claude لكتابة الرد النهائي
    // ================================================

    const groundedMessages = [
      ...messages,

      {
        role: 'assistant',
        content: rawExtraction,
      },

      {
        role: 'user',
        content: `[نتائج البحث الداخلية]
${resultsContext}

اكتب الرد النهائي للعميل بناءً على النتائج فقط.`,
      },
    ];


    const finalReply = await callClaude(
      GROUNDED_REPLY_SYSTEM_PROMPT,
      groundedMessages
    );


    // ================================================
    // لو الرد النهائي فشل
    // ================================================

    if (
      !finalReply ||
      typeof finalReply !== 'string' ||
      !finalReply.trim()
    ) {
      return CONTACT_REPLY;
    }


    return finalReply.trim();


  } catch (err) {

    // ================================================
    // أي خطأ غير متوقع
    // ================================================

    console.error(
      'خطأ غير متوقع في generateReply:',
      err
    );

    return CONTACT_REPLY;
  }
}


