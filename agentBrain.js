// قراءة JSON من Claude
// =====================================================

function tryParseClaudeResponse(
  rawText
) {

  if (
    !rawText ||
    typeof rawText !== 'string'
  ) {

    return null;
  }


  let cleaned =
    rawText
      .replace(
        /```json/gi,
        ''
      )
      .replace(
        /```/g,
        ''
      )
      .trim();


  try {

    return JSON.parse(
      cleaned
    );

  } catch (_) {
    // نكمل
  }


  const firstBrace =
    cleaned.indexOf('{');


  const lastBrace =
    cleaned.lastIndexOf('}');


  if (
    firstBrace !== -1 &&
    lastBrace !== -1 &&
    lastBrace >
      firstBrace
  ) {

    const possibleJson =
      cleaned.slice(
        firstBrace,
        lastBrace + 1
      );


    try {

      return JSON.parse(
        possibleJson
      );

    } catch (_) {
      // نص عادي
    }
  }


  return null;
}


