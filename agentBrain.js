// =====================================================
// الاتصال بـ Claude
// =====================================================

async function callClaude(system, messages, maxTokens = 1200) {

  try {

    const res = await axios.post(
      'https://api.anthropic.com/v1/messages',
      {
        model: MODEL,
        max_tokens: maxTokens,
        system,
        messages,
      },
      {
        headers: {
          'Content-Type': 'application/json',
          'x-api-key': ANTHROPIC_API_KEY,
          'anthropic-version': '2023-06-01',
        },
        timeout: 30000,
      }
    );

    return res.data.content
      .map((b) => b.text || '')
      .join('');

  } catch (err) {

    console.error(
      'تفاصيل خطأ Claude API:',
      JSON.stringify(
        err.response?.data || err.message,
        null,
        2
      )
    );

    return null;
  }
}


// =====================================================
// إنشاء الرد
// =====================================================

async function generateReply(history, userText) {

  try {

    // =================================================
    // فقط "تفاصيل أكثر" ترسل الرقم والقناة
    // =================================================

    if (customerAskedForMoreDetails(userText)) {

      return DETAILS_REPLY;

    }


    // =================================================
    // إرسال المحادثة كاملة للمساعد
    // حتى يعرف العقار الحالي
    // =================================================

    const messages = [
      ...history,
      {
        role: 'user',
        content: userText,
      },
    ];


    const rawExtraction = await callClaude(
      EXTRACTION_SYSTEM_PROMPT,
      messages
    );


    // =================================================
    // خطأ تقني
    // =================================================

    if (!rawExtraction) {

      return 'ياهلا فيك 🌹 ممكن تعيد رسالتك مرة ثانية؟';

    }


    // =================================================
    // تنظيف JSON
    // =================================================

    let cleaned = rawExtraction
      .replace(/```json/gi, '')
      .replace(/```/g, '')
      .trim();


    const firstBrace = cleaned.indexOf('{');
    const lastBrace = cleaned.lastIndexOf('}');


    if (
      firstBrace !== -1 &&
      lastBrace !== -1 &&
      lastBrace > firstBrace
    ) {

      cleaned = cleaned.slice(
        firstBrace,
        lastBrace + 1
      );

    }


    let parsed;


    // =================================================
    // قراءة JSON
    // =================================================

    try {

      parsed = JSON.parse(cleaned);

    } catch (e) {

      console.error(
        'فشل قراءة JSON من Claude:',
        cleaned
      );

      return 'ياهلا فيك 🌹 ممكن تعيد رسالتك مرة ثانية؟';

    }


    // =================================================
    // التأكد من صحة الرد
    // =================================================

    if (!parsed || typeof parsed !== 'object') {

      return 'ياهلا فيك 🌹 ممكن تعيد رسالتك مرة ثانية؟';

    }


    // =================================================
    // الرد الطبيعي
    // =================================================

    if (!parsed.ready_to_search) {

      if (
        parsed.reply &&
        typeof parsed.reply === 'string' &&
        parsed.reply.trim()
      ) {

        return parsed.reply.trim();

      }

      return 'ياهلا فيك 🌹 وش حاب تعرف عن العقار؟';

    }


    // =================================================
    // تجهيز معايير البحث
    // =================================================

    const criteria =
      parsed.criteria &&
      typeof parsed.criteria === 'object'
        ? parsed.criteria
        : {};


    // =================================================
    // البحث في قاعدة البيانات
    // =================================================

    let matches = [];

    try {

      matches =
        searchProperties({
          city: criteria.city || null,
          district: criteria.district || null,
          property_type: criteria.property_type || null,
          purpose: criteria.purpose || null,
          limit: 5,
        }) || [];

    } catch (searchError) {

      console.error(
        'خطأ أثناء البحث:',
        searchError
      );

      return 'ما قدرت أوصل لنتائج البحث حاليًا 🌹 جرب مرة ثانية بعد شوي.';

    }


    // =================================================
    // تجهيز نتائج البحث
    // =================================================

    const resultsContext = matches.length
      ? `نتائج البحث المتاحة فعليًا:\n${matches
          .map((m) => {

            const title =
              m.title ||
              m.property_type ||
              'عقار';

            const location =
              `${m.city || ''} ${m.district || ''}`.trim();

            const area =
              m.area_sqm
                ? `${m.area_sqm} م²`
                : 'المساحة غير مذكورة';

            const url =
              m.url ||
              'لا يوجد رابط';

            return `- ${title} في ${location} — ${area} — ${url}`;

          })
          .join('\n')}`
      : 'لا توجد نتائج مطابقة حاليًا في الفهرس.';


    // =================================================
    // الرد النهائي من نتائج البحث
    // =================================================

    const groundedMessages = [
      ...messages,

      {
        role: 'assistant',
        content: rawExtraction,
      },

      {
        role: 'user',
        content: `[نتائج البحث الداخلية]
${resultsContext}

اكتب الرد النهائي للعميل بناءً على النتائج فقط.
حافظ على سياق العقار الذي يتحدث عنه العميل.`,
      },
    ];


    const finalReply = await callClaude(
      GROUNDED_REPLY_SYSTEM_PROMPT,
      groundedMessages
    );


    if (
      !finalReply ||
      typeof finalReply !== 'string' ||
      !finalReply.trim()
    ) {

      return 'ما قدرت أوصل للنتيجة حاليًا 🌹 جرب مرة ثانية بعد شوي.';

    }


    return finalReply.trim();


  } catch (err) {

    console.error(
      'خطأ غير متوقع في generateReply:',
      err
    );

    return 'ياهلا فيك 🌹 ممكن تعيد رسالتك مرة ثانية؟';

  }
}


