// محاولة قراءة JSON
// =====================================================

function tryParseClaudeResponse(rawText) {

  if (!rawText || typeof rawText !== 'string') {
    return null;
  }

  let cleaned = rawText
    .replace(/```json/gi, '')
    .replace(/```/g, '')
    .trim();


  // المحاولة الأولى:
  // Claude رجع JSON نظيف
  try {

    return JSON.parse(cleaned);

  } catch (e) {
    // نكمل للمحاولة الثانية
  }


  // المحاولة الثانية:
  // Claude أضاف كلام قبل أو بعد JSON
  const firstBrace = cleaned.indexOf('{');
  const lastBrace = cleaned.lastIndexOf('}');

  if (
    firstBrace !== -1 &&
    lastBrace !== -1 &&
    lastBrace > firstBrace
  ) {

    const possibleJson = cleaned.slice(
      firstBrace,
      lastBrace + 1
    );

    try {

      return JSON.parse(possibleJson);

    } catch (e) {
      // ليس JSON
    }
  }


  // Claude رجع نص عادي
  return null;
}


