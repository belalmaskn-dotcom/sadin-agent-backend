// قراءة JSON
// =====================================================

function tryParseClaudeResponse(
  rawText
) {
  if (
    !rawText ||
    typeof rawText !== 'string'
  ) {
    return null;
  }


  let cleaned =
    rawText
      .replace(/```json/gi, '')
      .replace(/```/g, '')
      .trim();


  try {
    return JSON.parse(cleaned);

  } catch (e) {
    // نكمل
  }


  const firstBrace =
    cleaned.indexOf('{');

  const lastBrace =
    cleaned.lastIndexOf('}');


  if (
    firstBrace !== -1 &&
    lastBrace !== -1 &&
    lastBrace > firstBrace
  ) {
    const possibleJson =
      cleaned.slice(
        firstBrace,
        lastBrace + 1
      );

    try {
      return JSON.parse(
        possibleJson
      );

    } catch (e) {
      // نص عادي
    }
  }


  return null;
}


