function convertArabicDigits(text = '') {

  const arabicDigits = {
    '٠': '0',
    '١': '1',
    '٢': '2',
    '٣': '3',
    '٤': '4',
    '٥': '5',
    '٦': '6',
    '٧': '7',
    '٨': '8',
    '٩': '9',

    '۰': '0',
    '۱': '1',
    '۲': '2',
    '۳': '3',
    '۴': '4',
    '۵': '5',
    '۶': '6',
    '۷': '7',
    '۸': '8',
    '۹': '9',
  };


  return String(text).replace(
    /[٠-٩۰-۹]/g,
    (digit) =>
      arabicDigits[digit] ||
      digit
  );
}


// =====================================================
// تنظيف النص العربي
// =====================================================

function normalizeArabicText(
  text = ''
) {

  return convertArabicDigits(
    String(text)
  )
    .trim()
    .toLowerCase()

    .replace(/[أإآ]/g, 'ا')

    .replace(/ى/g, 'ي')

    .replace(
      /[ًٌٍَُِّْ]/g,
      ''
    )

    .replace(
      /[؟?!.,،]/g,
      ' '
    )

    .replace(
      /\s+/g,
      ' '
    )

    .trim();
}


