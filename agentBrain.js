// =====================================================
// استخراج الساعة
// =====================================================

function extractViewingTime(
  text = ''
) {

  const raw =
    convertArabicDigits(
      String(text || '')
    );


  const normalized =
    normalizeArabicText(
      raw
    );


  // -----------------------------------------------
  // الساعة 5
  // الساعة 5:30
  // الساعة 5 مساء
  // at 5
  // at 5 pm
  // -----------------------------------------------

  const explicitPatterns = [

    /(?:الساعة|الساعه)\s*(\d{1,2})(?::(\d{2}))?\s*(صباحا|صباح|مساء|العصر|الظهر|المغرب|الليل|م|ص)?/i,

    /\bat\s*(\d{1,2})(?::(\d{2}))?\s*(am|pm)?\b/i,

    /\b(\d{1,2}):(\d{2})\s*(am|pm|صباحا|صباح|مساء|العصر|الظهر|المغرب|الليل|م|ص)?\b/i,
  ];


  for (
    const pattern
    of explicitPatterns
  ) {

    const match =
      raw.match(pattern);


    if (match) {

      return match[0].trim();
    }
  }


  // -----------------------------------------------
  // الخامسة
  // خمسة
  // five
  // الساعة الخامسة
  // -----------------------------------------------

  const writtenHour =
    extractWrittenHour(
      normalized
    );


  if (writtenHour) {

    let suffix = '';


    if (
      normalized.includes(
        'مساء'
      ) ||
      normalized.includes(
        'pm'
      )
    ) {

      suffix = ' مساء';
    }


    else if (
      normalized.includes(
        'صباح'
      ) ||
      normalized.includes(
        'am'
      )
    ) {

      suffix = ' صباح';
    }


    else if (
      normalized.includes(
        'العصر'
      )
    ) {

      suffix = ' العصر';
    }


    else if (
      normalized.includes(
        'الظهر'
      )
    ) {

      suffix = ' الظهر';
    }


    else if (
      normalized.includes(
        'المغرب'
      )
    ) {

      suffix = ' المغرب';
    }


    else if (
      normalized.includes(
        'الليل'
      )
    ) {

      suffix = ' الليل';
    }


    return `${writtenHour}${suffix}`;
  }
    // -----------------------------------------------
  // لو البوت سأل عن الساعة
  // والعميل رد فقط:
  //
  // 5
  // ٥
  // -----------------------------------------------

  const onlyNumber =
    normalized.match(
      /^(\d{1,2})(?:\s*(am|pm|م|ص|مساء|صباح))?$/
    );


  if (onlyNumber) {

    const hour =
      Number(
        onlyNumber[1]
      );


    if (
      hour >= 1 &&
      hour <= 24
    ) {

      return normalized;
    }
  }


  return null;
}


