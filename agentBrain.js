async function generateReply(
  history,
  userText
) {
  try {

    // =================================================
    // مهم:
    // المعاينة لم تعد تتم هنا
    // server.js مسؤول عنها بالكامل
    // =================================================


    // =================================================
    // التمويل
    // =================================================

    if (
      customerAskedAboutFinance(
        userText
      )
    ) {
      return 'نعم، فيه تمويل 👍';
    }


    // =================================================
    // الرهن
    // =================================================

    if (
      customerAskedAboutMortgage(
        userText
      )
    ) {
      return 'لا، العقار ليس عليه رهن أبدًا.';
    }


    // =================================================
    // الإيجار
    // =================================================

    if (
      customerAskedAboutRent(
        userText
      )
    ) {
      return 'أيوه موجود، وفيه معارض ومكاتب وعماير، وإن شاء الله أرسل لك المتوفر الآن 🌹';
    }


    // =================================================
    // طلب تفاصيل أكثر
    // =================================================

    if (
      customerAskedForMoreDetails(
        userText
      )
    ) {
      console.log(
        'العميل طلب تفاصيل أكثر - إرسال بيانات التواصل'
      );

      return DETAILS_REPLY;
    }


    // =================================================
    // إرسال المحادثة لـ Claude
    // =================================================

    const messages = [
      ...history,

      {
        role: 'user',
        content: userText,
      },
    ];


    const rawExtraction =
      await callClaude(
        EXTRACTION_SYSTEM_PROMPT,
        messages
      );


    if (!rawExtraction) {
      console.error(
        'Claude لم يرجع أي محتوى'
      );

      return 'ياهلا فيك 🌹 ممكن تعيد رسالتك مرة ثانية؟';
    }


    const parsed =
      tryParseClaudeResponse(
        rawExtraction
      );


    if (!parsed) {
      console.log(
        'Claude رجع نص عادي - سيتم إرساله مباشرة للعميل'
      );

      return rawExtraction.trim();
    }


    if (
      parsed.ready_to_search !== true
    ) {
      if (
        parsed.reply &&
        typeof parsed.reply ===
          'string' &&
        parsed.reply.trim()
      ) {
        return parsed.reply.trim();
      }


      return 'ياهلا فيك 🌹 وش حاب تعرف عن العقار؟';
    }


    const criteria =
      parsed.criteria &&
      typeof parsed.criteria ===
        'object'
        ? parsed.criteria
        : {};


    let matches = [];


    try {
      matches =
        searchProperties({
          city:
            criteria.city ||
            null,

          district:
            criteria.district ||
            null,

          property_type:
            criteria.property_type ||
            null,

          purpose:
            criteria.purpose ||
            null,

          limit:
            5,
        }) || [];

    } catch (searchError) {
      console.error(
        'خطأ أثناء البحث:',
        searchError
      );


      return 'ما قدرت أوصل لنتائج البحث حاليًا 🌹 جرب مرة ثانية بعد شوي.';
    }


    const resultsContext =
      matches.length
        ? `نتائج البحث المتاحة فعليًا:\n${matches
            .map(
              (m) => {

                const title =
                  m.title ||
                  m.property_type ||
                  'عقار';


                const location =
                  `${m.city || ''} ${m.district || ''}`.trim();


                const area =
                  m.area_sqm
                    ? `${m.area_sqm} م²`
                    : 'المساحة غير مذكورة';


                const url =
                  m.url ||
                  'لا يوجد رابط';


                return `- ${title} في ${location} — ${area} — ${url}`;
              }
            )
            .join('\n')}`

        : 'لا توجد نتائج مطابقة حاليًا في الفهرس.';


    const groundedMessages = [
      ...messages,

      {
        role: 'assistant',
        content: rawExtraction,
      },

      {
        role: 'user',

        content:
`[نتائج البحث الداخلية]
${resultsContext}

اكتب الرد النهائي للعميل بناءً على النتائج فقط.
حافظ على سياق العقار الذي يتحدث عنه العميل.
إذا سأل عن تفصيلة واحدة جاوب عنها فقط.`,
      },
    ];


    const finalReply =
      await callClaude(
        GROUNDED_REPLY_SYSTEM_PROMPT,
        groundedMessages
      );


    if (
      !finalReply ||
      typeof finalReply !==
        'string' ||
      !finalReply.trim()
    ) {
      return 'ما قدرت أوصل للنتيجة حاليًا 🌹 جرب مرة ثانية بعد شوي.';
    }


    return finalReply.trim();


  } catch (err) {
    console.error(
      'خطأ غير متوقع في generateReply:',
      err
    );


    return 'ياهلا فيك 🌹 ممكن تعيد رسالتك مرة ثانية؟';
  }
}


