function customerAskedForMoreDetails(text = '') {

  const normalized = String(text)
    .trim()
    .toLowerCase()
    .replace(/[؟?!.,،]/g, ' ')
    .replace(/\s+/g, ' ');

  const triggerPhrases = [
    'ممكن تفاصيل اكثر',
    'ممكن تفاصيل أكثر',
    'تفاصيل اكثر',
    'تفاصيل أكثر',
    'ابي تفاصيل اكثر',
    'ابي تفاصيل أكثر',
    'أبي تفاصيل اكثر',
    'أبي تفاصيل أكثر',
    'ابغى تفاصيل اكثر',
    'ابغى تفاصيل أكثر',
    'أبغى تفاصيل اكثر',
    'أبغى تفاصيل أكثر',
    'اريد تفاصيل اكثر',
    'أريد تفاصيل أكثر',
    'ودي بتفاصيل اكثر',
    'ودي بتفاصيل أكثر'
  ];

  return triggerPhrases.some((phrase) =>
    normalized.includes(
      phrase
        .toLowerCase()
        .replace(/[؟?!.,،]/g, ' ')
        .replace(/\s+/g, ' ')
    )
  );
}


