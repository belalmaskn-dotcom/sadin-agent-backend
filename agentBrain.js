function normalizeArabicText(text = '') {
  return String(text)
    .trim()
    .toLowerCase()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/[ًٌٍَُِّْ]/g, '')
    .replace(/[؟?!.,،]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}


function customerAskedForMoreDetails(text = '') {

  const normalized = normalizeArabicText(text);

  const triggerPhrases = [
    'ممكن تفاصيل اكثر',
    'تفاصيل اكثر',
    'ابي تفاصيل اكثر',
    'ابغى تفاصيل اكثر',
    'اريد تفاصيل اكثر',
    'ودي بتفاصيل اكثر'
  ];

  return triggerPhrases.some((phrase) =>
    normalized.includes(
      normalizeArabicText(phrase)
    )
  );
}


